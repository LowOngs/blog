#!/usr/bin/env node
/**
 * ============================================================================
 * AOIA
 * File : System_files/tools/patch/normalize-subscription-trend.cjs
 * Role : Normalize Trend Subscription Seed Structure
 * ============================================================================
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "../../");
const TARGET = path.join(
  ROOT,
  "seedpool",
  "warehouse",
  "trend",
  "subscription-services-trend.json"
);

if (!fs.existsSync(TARGET)) {
  console.error("[ERROR] file not found");
  console.error(TARGET);
  process.exit(1);
}

const raw = fs.readFileSync(TARGET, "utf8");
const json = JSON.parse(raw);

const beforeCount = Array.isArray(json.trend)
  ? json.trend.length
  : 0;

let removedAutoGenerated = 0;
let normalized = 0;

json.trend = (json.trend || []).filter(item => {
  const title = String(item.title || "");

  const isAuto =
    title.includes("AUTO GENERATED:");

  if (isAuto) {
    removedAutoGenerated++;
    return false;
  }

  return true;
});

for (const item of json.trend) {

  item.reviewEntity ||= {};

  const service =
    item.reviewEntity.service ||
    item.service ||
    item.environment ||
    "Unknown Service";

  item.reviewEntity.type ||= "subscription";
  item.reviewEntity.service ||= service;

  item.reviewEntity.category ||=
    String(item.environment || "general")
      .toLowerCase()
      .replace(/\s+/g, "-");

  item.reviewEntity.billingModel ||= "monthly";

  item.subscriptionHints ||= {
    billingModel: "monthly",
    freeTier: true,
    trialAvailable: true,
    familyPlan: false,
    planCount: 3
  };

  item.changeSignals ||= {
    priceChange: false,
    planChange: false,
    featureExpansion: true,
    restrictionChange: false,
    competitorPressure: true
  };

  item.decisionType ||= "review/still-worth";

  item.decisionSummary ||= {
    primaryQuestion:
      "Is this subscription still worth paying for?",
    focus:
      "value-for-money"
  };

  item.trendContext ||= {
    historicalValue: true,
    reviewWindow: "30-90 days",
    currentUse:
      "subscription decision support",
    laterUse:
      "historical comparison record"
  };

  item.useCases ||= [];const categoryText = (
  item.reviewEntity.category ||
  item.environment ||
  ""
).toLowerCase();

const USE_CASE_RULES = [
  {
    match: ["vpn"],
    useCases: [
      "travel streaming",
      "public wifi privacy",
      "remote work access"
    ]
  },
  {
    match: ["ai-photo", "ai photo"],
    useCases: [
      "creator image editing",
      "product image cleanup",
      "social media export"
    ]
  },
  {
    match: ["password"],
    useCases: [
      "credential management",
      "family account sharing",
      "security monitoring"
    ]
  },
  {
    match: ["backup"],
    useCases: [
      "device recovery",
      "work file restore",
      "family photo backup"
    ]
  },
  {
    match: ["video", "streaming"],
    useCases: [
      "home entertainment",
      "family viewing",
      "content discovery"
    ]
  },
  {
    match: ["music"],
    useCases: [
      "daily listening",
      "playlist management",
      "offline playback"
    ]
  },
  {
    match: ["cloud gaming", "gaming"],
    useCases: [
      "device independent gaming",
      "high-end game access",
      "cross-device play"
    ]
  },
  {
    match: ["language"],
    useCases: [
      "travel preparation",
      "exam study",
      "daily conversation practice"
    ]
  },
  {
    match: ["productivity"],
    useCases: [
      "team collaboration",
      "task management",
      "document workflow"
    ]
  },
  {
    match: ["ai-chat", "ai chat"],
    useCases: [
      "research assistance",
      "content drafting",
      "daily productivity"
    ]
  }
];

if (!Array.isArray(item.useCases) || item.useCases.length === 0) {
  const matched = USE_CASE_RULES.find(rule =>
    rule.match.some(keyword => categoryText.includes(keyword))
  );

  item.useCases = matched
    ? [...matched.useCases]
    : [
        "service evaluation",
        "value comparison",
        "subscription decision support"
      ];
}

  normalized++;
}

const backup =
  TARGET.replace(
    ".json",
    `.backup-${Date.now()}.json`
  );

fs.copyFileSync(TARGET, backup);

fs.writeFileSync(
  TARGET,
  JSON.stringify(json, null, 2),
  "utf8"
);

console.log("────────────────────────────");
console.log("[normalize-subscription-trend]");
console.log("target =", TARGET);
console.log("backup =", backup);
console.log("before =", beforeCount);
console.log("after  =", json.trend.length);
console.log("removedAutoGenerated =", removedAutoGenerated);
console.log("normalized =", normalized);
console.log("────────────────────────────");
